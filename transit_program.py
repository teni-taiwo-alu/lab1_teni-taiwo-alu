import os
from datetime import datetime
from engine import log, set_time, set_driver_name, start_road_engine, update_road

LOG_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "transit_session.log")
s = None  # your road_simulation module, set by run()


def get_lane(sign):
    if s.get_sign_type(sign) == "bus":
        return "LEFT"
    return "RIGHT"


def ask_for_name():
    name = input("Enter your driver name: ").strip()
    if name == "":
        name = "Driver"
    return name[:14]


def get_stop_time(sign):
    if s.get_sign_type(sign) == "zebra":
        return s.ZEBRA_WAIT
    return 0


def write_log(message, level="info"):
    log(message, level)
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    with open(LOG_FILE, "a") as file:
        file.write(f"{now} [{level.upper()}] {message}\n")


def start_log_session():
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    with open(LOG_FILE, "a") as file:
        file.write(f"\n===== New session started {now} =====\n")


def new_report():
    return {
        "max_speed": 0,
        "seconds_stopped": 0,
        "lane_changes": 0,
    }


def update_report(report, speed, limit, stop_timer):
    if speed > report["max_speed"]:
        report["max_speed"] = speed
    if speed == 0 and stop_timer > 0:
        report["seconds_stopped"] = report["seconds_stopped"] + 1


def ask_for_sign():
    sign = input("Which sign? (bus, zebra, or a speed limit like 80): ").strip().lower()
    if not s.is_valid_sign(sign):
        print("  Not allowed! Use 'bus', 'zebra', or a number from 20 to 100.")
        return None
    return sign


def show_road(road_list):
    print("\nTHE ROAD ARRAY (each item = 100 m):")
    print(road_list)
    print()
    for i in range(len(road_list)):
        print(f"  segment {i:>2}: {road_list[i]}")
    speed_signs, zebras, buses = s.count_signs(road_list)
    print(f"  -> {len(road_list)} segments: {speed_signs} speed limit signs, "
          f"{zebras} zebra crossings, {buses} bus segments")


def road_menu(road_list):
    while True:
        print("\n--- ROAD EDITOR ---")
        print("1. Add a sign at the end")
        print("2. Insert a sign at a segment number")
        print("3. Replace a sign at a segment index")
        print("4. Show the road")
        print("5. Start driving")
        choice = s.ask_for_number("Choose 1-5: ", 1, 5)

        if choice == 1:
            sign = ask_for_sign()
            if sign is not None:
                road_list.append(sign)
                write_log(f"Added '{sign}' at segment {len(road_list) - 1}")
        elif choice == 2:
            sign = ask_for_sign()
            if sign is not None:
                position = s.ask_for_number(f"Segment number (0-{len(road_list)}): ", 0, len(road_list))
                if s.insert_sign(road_list, sign, position):
                    write_log(f"Inserted '{sign}' at segment {position}")
                else:
                    print("  Could not insert the sign. Check your insert_sign function.")
        elif choice == 3:
            if len(road_list) == 0:
                print("  The road is empty, there is nothing to replace.")
            else:
                sign = ask_for_sign()
                if sign is not None:
                    index = s.ask_for_number(f"Segment index (0-{len(road_list) - 1}): ", 0, len(road_list) - 1)
                    old_sign = road_list[index]
                    if s.replace_sign(road_list, sign, index):
                        write_log(f"Replaced '{old_sign}' with '{sign}' at segment {index}")
                    else:
                        print("  Could not replace the sign. Check your replace_sign function.")
        elif choice == 4:
            show_road(road_list)
        else:
            if len(road_list) == 0:
                print("  Add at least one sign first.")
            else:
                break


def print_report(driver_name, report, seconds, road_list):
    signs_passed, length_m, start_name, end_name = s.get_journey_summary(road_list)
    average = round(length_m / seconds * 3.6, 1)
    lines = [
        "----- TRIP REPORT -----",
        f"Driver            : {driver_name}",
        f"Started at        : {start_name}",
        f"Finished at       : {end_name}",
        f"Road length       : {length_m} m",
        f"Signs passed      : {signs_passed}",
        f"Total time        : {seconds} s",
        f"Average speed     : {average} km/h",
        f"Top speed         : {report['max_speed']} km/h",
        f"Time stopped      : {report['seconds_stopped']} s",
        f"Lane changes      : {report['lane_changes']}",
    ]
    for line in lines:
        print(line)
        write_log(line, "ok")


def run(student):
    global s
    s = student
    road = s.road
    start_log_session()
    driver_name = ask_for_name()
    set_driver_name(driver_name)
    show_road(road)
    road_menu(road)

    print("\n" + "=" * 60)
    print("FINAL ROAD - the car is about to drive on this array:")
    print("=" * 60)
    show_road(road)

    start_road_engine(road)
    input("\nOpen the visual link above, then press ENTER here to start driving...\n")

    position_m = 0.0
    speed = 0
    limit = 60
    lane = "RIGHT"
    stop_timer = 0
    report = new_report()

    current_segment = -1
    seconds = 0
    road_length_m = len(road) * s.SEGMENT_M

    write_log(f"{driver_name} begins the journey at {s.START_NAME}!", "ok")

    while position_m < road_length_m:
        seconds = seconds + 1
        set_time(seconds)

        new_segment = int(position_m // s.SEGMENT_M)
        if new_segment != current_segment:
            current_segment = new_segment
            sign = road[current_segment]

            if s.get_sign_type(sign) != "road":
                write_log(f"Segment {current_segment}: sign '{sign}'")

            new_limit = s.get_speed_limit(sign, limit)
            if new_limit != limit:
                write_log(f"Speed limit changes from {limit} to {new_limit} km/h")
                limit = new_limit

            wait_time = get_stop_time(sign)
            if wait_time > 0:
                write_log(f"Zebra crossing! Stopping for {wait_time} seconds", "warn")
                stop_timer = wait_time

        new_lane = get_lane(road[current_segment])
        if new_lane != lane:
            write_log(f"Changing lane: {lane} -> {new_lane}", "warn")
            lane = new_lane
            report["lane_changes"] = report["lane_changes"] + 1

        target = s.get_target_speed(limit, stop_timer)
        speed = s.adjust_speed(speed, target)

        if speed == 0 and stop_timer > 0:
            stop_timer = stop_timer - 1
            write_log(f"Waiting at the zebra crossing... {stop_timer}s left")

        update_report(report, speed, limit, stop_timer)
        position_m = position_m + speed / 3.6

        if seconds % 10 == 0:
            write_log(f"Speed {speed} km/h | limit {limit} | lane {lane}")

        next_text = "none"
        for i in range(current_segment + 1, len(road)):
            if s.get_sign_type(road[i]) != "road":
                next_text = f"{road[i]} in {i - current_segment} segments"
                break

        if stop_timer > 0 and speed == 0:
            status = f"Waiting at zebra: {stop_timer}s"
        elif speed < target:
            status = "Accelerating"
        elif speed > target:
            status = "Braking"
        else:
            status = "Cruising"

        update_road(position_m, speed, limit, lane, next_text, status, seconds)

    write_log(f"Arrived at {s.END_NAME} in {seconds} seconds!", "ok")
    update_road(position_m, 0, limit, lane, "none", "Finished", seconds)
    print_report(driver_name, report, seconds, road)
    print("\nSUCCESS! The car completed the whole road.")
    input("Press Enter to close...")
